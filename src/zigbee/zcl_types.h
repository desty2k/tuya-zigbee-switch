#ifndef ZIGBEE_ZCL_TYPES_H_
#define ZIGBEE_ZCL_TYPES_H_

/* Shared Zigbee Cluster Library wire data types. */
#define ZCL_DATA_TYPE_NO_DATA           0x00u
#define ZCL_DATA_TYPE_DATA8             0x08u
#define ZCL_DATA_TYPE_DATA16            0x09u
#define ZCL_DATA_TYPE_DATA24            0x0Au
#define ZCL_DATA_TYPE_DATA32            0x0Bu
#define ZCL_DATA_TYPE_DATA40            0x0Cu
#define ZCL_DATA_TYPE_DATA48            0x0Du
#define ZCL_DATA_TYPE_DATA56            0x0Eu
#define ZCL_DATA_TYPE_DATA64            0x0Fu
#define ZCL_DATA_TYPE_BOOLEAN           0x10u
#define ZCL_DATA_TYPE_BITMAP8           0x18u
#define ZCL_DATA_TYPE_BITMAP16          0x19u
#define ZCL_DATA_TYPE_BITMAP24          0x1Au
#define ZCL_DATA_TYPE_BITMAP32          0x1Bu
#define ZCL_DATA_TYPE_UINT8             0x20u
#define ZCL_DATA_TYPE_UINT16            0x21u
#define ZCL_DATA_TYPE_UINT24            0x22u
#define ZCL_DATA_TYPE_UINT32            0x23u
#define ZCL_DATA_TYPE_INT8              0x28u
#define ZCL_DATA_TYPE_INT16             0x29u
#define ZCL_DATA_TYPE_INT32             0x2Au
#define ZCL_DATA_TYPE_ENUM8             0x30u
#define ZCL_DATA_TYPE_ENUM16            0x31u
#define ZCL_DATA_TYPE_OCTET_STR         0x41u
#define ZCL_DATA_TYPE_CHAR_STR          0x42u
#define ZCL_DATA_TYPE_LONG_OCTET_STR    0x43u
#define ZCL_DATA_TYPE_LONG_CHAR_STR     0x44u

#endif
